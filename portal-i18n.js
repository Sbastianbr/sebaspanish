export function language() { return Object.hasOwn(copy, document.documentElement.lang) ? document.documentElement.lang : 'es'; }
export function t(key, values = {}) {
  let value = copy[language()][key] ?? copy.es[key] ?? copy.es.unspecified;
  for (const [name, text] of Object.entries(values)) value = value.replace(`{${name}}`, String(text));
  return value;
}
export function translatePage() {
  document.querySelectorAll('[data-portal-i18n]').forEach((el) => { el.textContent = t(el.dataset.portalI18n); });
  document.title = `SebaSpanish · ${t(document.body.dataset.portalPage === 'access' ? 'access' : document.body.dataset.portalPage === 'callback' ? 'callback' : 'page')}`;
}
export function watchLanguage(render = () => {}) {
  const update = () => { translatePage(); render(); };
  update();
  const observer = new MutationObserver(update);
  observer.observe(document.documentElement, { attributes: true, attributeFilter: ['lang'] });
  return () => observer.disconnect();
}
export function date(value, timeZone, withTime = false) {
  if (!value || !Number.isFinite(Date.parse(value))) return t('unspecified');
  return new Intl.DateTimeFormat({ es: 'es-ES', en: 'en-GB', pl: 'pl-PL' }[language()], {
    dateStyle: 'medium', ...(withTime ? { timeStyle: 'short' } : {}), timeZone,
  }).format(new Date(value));
}
export function money(minor, currency) { return new Intl.NumberFormat(language(), { style: 'currency', currency }).format(minor / 100); }
